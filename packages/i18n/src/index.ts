export type MessageId = keyof typeof enUS;

/** The language every catalog falls back to (SET-LIFE-08). */
export const NEUTRAL_LOCALE = "en-US";

/** A complete set of messages for one language, keyed by every `MessageId`. */
export type Catalog = Readonly<Record<MessageId, string>>;

export type MessageValues = Readonly<Record<string, string | number>>;

export type Translate = (id: MessageId, values?: MessageValues) => string;

/**
 * Formats messages with FormatJS (ICU MessageFormat) for one locale. Each message is parsed on
 * first use and then reused.
 */
export function createTranslator(locale: string, catalog: Catalog): Translate {
  const formats = new Map<MessageId, IntlMessageFormat>();
  return (id, values) => {
    let format = formats.get(id);
    if (format === undefined) {
      format = new IntlMessageFormat(catalog[id], locale);
      formats.set(id, format);
    }
    return format.format(values) as string;
  };
}

/** Translates a message id with the neutral English catalog. */
export const t: Translate = createTranslator(NEUTRAL_LOCALE, enUS);
